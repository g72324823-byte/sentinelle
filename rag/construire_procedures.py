def rendre(p) -> str:
    ident, titre, hab, date, objet, etapes, regles = p
    lignes = ["---", f"id: {ident}", f"titre: \"{titre}\"", "version: 1", f"date: {date}",
              f"habilitation: {hab}", "---", "", f"# {ident} — {titre}", "", "## Objet", "", objet, "",
              "## Déroulement", ""]
    lignes += [f"{i}. {e}" for i, e in enumerate(etapes, 1)]
    lignes += ["", "## Règles et seuils", ""] + [f"- {r}" for r in regles] + [""]
    return "\n".join(lignes)


